#!/usr/bin/env python3
"""Generate/check capability docs from the executable registries, not constants."""
import argparse
import json
from pathlib import Path
import subprocess
import sys

ROOT = Path(__file__).resolve().parent.parent
WORKSPACE = ROOT / "src/barzakh-scanner-rs"
START = "<!-- capabilities:start -->"
END = "<!-- capabilities:end -->"


def render():
    names = json.loads(subprocess.check_output([
        "cargo", "run", "--quiet", "--locked", "-p", "barzakh-cli", "--bin",
        "barzakh-scanner", "--", "detectors", "list", "--json",
    ], cwd=WORKSPACE, text=True))
    if len(names) != len(set(names)):
        raise RuntimeError("duplicate detector names in registry")
    names.sort()
    return (
        "# Generated detector capabilities\n\n"
        "<!-- Generated by scripts/update-capabilities.py; do not edit. -->\n\n"
        f"Registered built-in detectors: **{len(names)}**. Registration is not a claim of\n"
        "independent validation, cryptographic verification, or runtime coverage.\n\n"
        + "\n".join(f"- `{name}`" for name in names) + "\n"
    ), f"{START}\n**{len(names)} registered built-in detectors** — [generated registry](docs/CAPABILITIES.md).\n{END}"


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    capability, summary = render()
    readme = ROOT / "README.md"
    current = readme.read_text()
    before, remainder = current.split(START, 1)
    _, after = remainder.split(END, 1)
    outputs = {ROOT / "docs/CAPABILITIES.md": capability, readme: before + summary + after}
    stale = []
    for path, expected in outputs.items():
        if args.check:
            if not path.exists() or path.read_text() != expected:
                stale.append(str(path.relative_to(ROOT)))
        else:
            path.write_text(expected)
    if stale:
        print("Stale generated docs: " + ", ".join(stale), file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
